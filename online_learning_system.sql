-- ============================================================
-- STEP 1: DELETE OLD TABLES
-- ============================================================
DROP TABLE PAYMENT    CASCADE CONSTRAINTS;
DROP TABLE ENROLLS    CASCADE CONSTRAINTS;
DROP TABLE QUIZ       CASCADE CONSTRAINTS;
DROP TABLE CONTENT    CASCADE CONSTRAINTS;
DROP TABLE COURSE     CASCADE CONSTRAINTS;
DROP TABLE INSTRUCTOR CASCADE CONSTRAINTS;
DROP TABLE STUDENT    CASCADE CONSTRAINTS;

-- ============================================================
-- STEP 2: CREATE TABLES
-- ============================================================

CREATE TABLE STUDENT (
    STUDENT_ID    NUMBER(5)     PRIMARY KEY,
    STUDENT_NAME  VARCHAR2(50)  NOT NULL
);

CREATE TABLE INSTRUCTOR (
    INSTRUCTOR_ID    NUMBER(5)     PRIMARY KEY,
    INSTRUCTOR_NAME  VARCHAR2(50)  NOT NULL
);

CREATE TABLE COURSE (
    COURSE_ID      NUMBER(5)     PRIMARY KEY,
    COURSE_TITLE   VARCHAR2(100) NOT NULL,
    INSTRUCTOR_ID  NUMBER(5)     NOT NULL,
    CONSTRAINT fk_course_instructor
        FOREIGN KEY (INSTRUCTOR_ID) REFERENCES INSTRUCTOR(INSTRUCTOR_ID)
);

CREATE TABLE ENROLLS (
    ENROLL_ID   NUMBER(5) PRIMARY KEY,
    STUDENT_ID  NUMBER(5) NOT NULL,
    COURSE_ID   NUMBER(5) NOT NULL,
    CONSTRAINT fk_enrolls_student
        FOREIGN KEY (STUDENT_ID) REFERENCES STUDENT(STUDENT_ID),
    CONSTRAINT fk_enrolls_course
        FOREIGN KEY (COURSE_ID) REFERENCES COURSE(COURSE_ID)
);

CREATE TABLE CONTENT (
    CONTENT_ID    NUMBER(5)    PRIMARY KEY,
    CONTENT_TYPE  VARCHAR2(30) NOT NULL,
    COURSE_ID     NUMBER(5)    NOT NULL,
    CONSTRAINT fk_content_course
        FOREIGN KEY (COURSE_ID) REFERENCES COURSE(COURSE_ID)
);

CREATE TABLE QUIZ (
    QUIZ_ID      NUMBER(5)     PRIMARY KEY,
    QUIZ_TITLE   VARCHAR2(100) NOT NULL,
    TOTAL_MARKS  NUMBER(5)     NOT NULL,
    COURSE_ID    NUMBER(5)     NOT NULL,
    CONSTRAINT fk_quiz_course
        FOREIGN KEY (COURSE_ID) REFERENCES COURSE(COURSE_ID)
);

CREATE TABLE PAYMENT (
    PAYMENT_ID  NUMBER(5)    PRIMARY KEY,
    ENROLL_ID   NUMBER(5)    NOT NULL,
    AMOUNT      NUMBER(8,2)  NOT NULL,
    STATUS      VARCHAR2(20) NOT NULL,
    CONSTRAINT fk_payment_enroll
        FOREIGN KEY (ENROLL_ID) REFERENCES ENROLLS(ENROLL_ID)
);

