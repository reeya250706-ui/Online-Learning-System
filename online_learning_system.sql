-- ============================================================
-- STEP 4: JOIN QUERY (all tables combined)
-- ============================================================

SELECT S.STUDENT_ID,
       S.STUDENT_NAME,
       C.COURSE_ID,
       C.COURSE_TITLE,
       I.INSTRUCTOR_NAME,
       CT.CONTENT_TYPE,
       Q.QUIZ_TITLE,
       Q.TOTAL_MARKS,
       P.AMOUNT,
       P.STATUS
FROM   STUDENT    S
JOIN   ENROLLS    E  ON E.STUDENT_ID    = S.STUDENT_ID
JOIN   COURSE     C  ON C.COURSE_ID     = E.COURSE_ID
JOIN   INSTRUCTOR I  ON I.INSTRUCTOR_ID = C.INSTRUCTOR_ID
JOIN   CONTENT    CT ON CT.COURSE_ID    = C.COURSE_ID
JOIN   QUIZ       Q  ON Q.COURSE_ID     = C.COURSE_ID
JOIN   PAYMENT    P  ON P.ENROLL_ID     = E.ENROLL_ID
ORDER  BY S.STUDENT_ID;
